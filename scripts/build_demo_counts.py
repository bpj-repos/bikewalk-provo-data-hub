"""Build the synthetic hosting proof in a new directory. No private inputs."""
import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

DATASET = 'annual-transportation-counts'
VERSIONS = ['1.0.0-demo.1', '1.0.0-demo.2']
FIELDS = {
    'year': ('integer', 'Source count year'),
    'station_id': ('string', 'Station identifier in its documented source namespace'),
    'period': ('string', 'Source session or combined period'),
    'mode': ('string', 'Travel mode or all'),
    'breakdown': ('string', 'Reported total or identified component'),
    'unit': ('string', 'Number of observations'),
    'source_field': ('string', 'Original source column'),
    'status': ('string', 'observed, missing, or unavailable'),
    'value': ('integer', 'Nonnegative count; blank for missing or unavailable'),
}


def check_version(previous, proposed, change):
    """Check a stable release bump against the owner's reviewed classification."""
    major, minor, patch = map(int, previous.split('.'))
    expected_version = {'breaking': (major + 1, 0, 0),
                        'compatible': (major, minor + 1, 0),
                        'correction': (major, minor, patch + 1)}[change]
    if proposed != '.'.join(map(str, expected_version)):
        raise ValueError(f'Incorrect {change} version: {proposed}')


def encoded(value):
    return (json.dumps(value, indent=2, ensure_ascii=False) + '\n').encode()


def csv_bytes(rows):
    stream = io.StringIO(newline='')
    writer = csv.writer(stream, lineterminator='\n')
    writer.writerow(FIELDS)
    writer.writerows(rows)
    return stream.getvalue().encode()


def package(version):
    years = [2001] if version == VERSIONS[0] else [2001, 2002]
    rows = [(year, 'demo-A', 'combined', mode, 'total', 'observations', field, status, value)
            for year in years for mode, field, status, value in [
                ('bicycle', 'demo_bike', 'observed', 0),
                ('walking', 'demo_walk', 'missing', ''),
                ('scooter', 'demo_scoot', 'unavailable', '')]]
    files = {'series.csv': csv_bytes(rows)}
    for year in years:
        files[f'{year}.csv'] = csv_bytes([row for row in rows if row[0] == year])
    files['dictionary.json'] = encoded({'fields': [
        dict(name=k, type=v[0], description=v[1]) for k, v in FIELDS.items()]})
    files['protocol.md'] = b'Synthetic station and years for a hosting example. No field observations.\n'
    files['mapping.md'] = b'All demo fields are invented. No equivalence to a historical field protocol is claimed.\n'
    files['changes.md'] = ('Initial synthetic fixture.\n' if len(years) == 1 else
                           'Adds synthetic year 2002 with the same field definitions.\n').encode()
    manifest = dict(name=DATASET, version=version, title='Synthetic annual counts hosting proof',
                    synthetic=True, coverage=years, sourceDate='2026-11-07',
                    preparation='Deterministic invented rows generated by release.py',
                    attribution='BikeWalk Provo', reuse='Synthetic demonstration files may be freely reused.',
                    citation=f'BikeWalk Provo. Synthetic annual counts hosting proof, {version}.',
                    resources=[dict(name=Path(path).stem, path=path, bytes=len(data),
                                    hash='sha256:' + hashlib.sha256(data).hexdigest())
                               for path, data in files.items()])
    files['datapackage.json'] = encoded(manifest)
    return files


def expected(versions):
    files = {}
    releases = []
    for version in versions:
        prefix = f'datasets/{DATASET}/{version}/'
        for path, data in package(version).items():
            files[prefix + path] = data
        manifest = prefix + 'datapackage.json'
        releases.append(dict(version=version, manifest='/' + manifest,
                             sha256=hashlib.sha256(files[manifest]).hexdigest()))
    pins = json.loads((Path(__file__).resolve().parents[1]/'releases/baseline-pins/demo-counts.json').read_text())['datasets'][0]['releases']
    if releases != pins[:len(releases)]:
        raise ValueError('Published manifest changed under an existing pin')
    files['catalog.json'] = encoded(dict(synthetic=True, datasets=[dict(id=DATASET,
                                      current=versions[-1], releases=releases)]))
    return files


def validate(root, versions):
    files = expected(versions)
    actual = {p.relative_to(root).as_posix() for p in root.rglob('*') if p.is_file()}
    if actual != set(files):
        raise ValueError('Missing or unexpected public files')
    for path, data in files.items():
        if (root / path).read_bytes() != data:
            raise ValueError(f'Content mismatch: {path}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['build', 'validate'])
    parser.add_argument('output', type=Path)
    parser.add_argument('--first', action='store_true')
    args = parser.parse_args()
    versions = VERSIONS[:1] if args.first else VERSIONS
    if args.action == 'build':
        args.output.mkdir(parents=True, exist_ok=False)
        for path, data in expected(versions).items():
            target = args.output / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    validate(args.output, versions)
